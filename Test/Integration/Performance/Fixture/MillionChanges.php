declare(strict_types=1);

namespace Hryvinskyi\AdminActionLog\Test\Integration\Performance\Fixture;

use Hryvinskyi\AdminActionLog\Model\ResourceModel\EntityChangeStore;
use Magento\Framework\App\ResourceConnection;

/**
 * A journal of a million activities over a year, four in ten of them entity changes with their change and field rows
 *
 * Changes are of products (six in ten), settings (two), categories and CMS blocks (one each); each has two or three
 * field rows, a fifth of them recorded unchanged as a snapshot keeps them, one in fifty masked, a few holding
 * "cotton". The rows are generated by the database (MariaDB's SEQUENCE engine), outside any test transaction, and
 * removed afterwards; a complete seed left by an interrupted run is reused.
 */
class MillionChanges
{
    public const ROWS = 1_000_000;
    public const NOW_MS = 1_960_000_000_000;
    public const SPAN_MS = 31_536_000_000;
    public const CORRELATION_PREFIX = 'aalperf-';
    public const RARE_PATH = 'aalperf/rare/enabled';
    private const JOURNAL_TABLE = 'hryvinskyi_activity_log';

    /**
     * @param ResourceConnection $resourceConnection
     */
    public function __construct(
        private readonly ResourceConnection $resourceConnection
    ) {
    }

    /**
     * Write the journal and the changes, unless a complete seed is already there
     *
     * @return void
     */
    public function seed(): void
    {
        if ($this->seededRows() === self::ROWS) {
            return;
        }

        $this->remove();
        $connection = $this->resourceConnection->getConnection();
        $journal = $this->table(self::JOURNAL_TABLE);
        $stepMs = intdiv(self::SPAN_MS, self::ROWS);
        $firstMs = self::NOW_MS - self::ROWS * $stepMs;
        $type = "ELT(1 + FLOOR(seq / 5) % 10, 'product', 'product', 'product', 'product', 'product', 'product',
            'config_value', 'config_value', 'category', 'cms_block')";

        $connection->query(
            "INSERT INTO {$journal} (correlation_id, channel, action, subject_type, subject_id, subject_label,
                actor_type, actor_name, outcome, store_id, occurred_at_ms, created_at)
            SELECT CONCAT('" . self::CORRELATION_PREFIX . "', LPAD(FLOOR(seq / 3), 8, '0')),
                IF(seq % 5 < 2, 'entity', ELT(1 + seq % 3, 'zz_request', 'zz_api', 'zz_agent')),
                IF(seq % 5 < 2, 'Record saved', ELT(1 + seq % 4, 'POST /items', 'GET /reports', 'Page opened',
                    'run nightly_import.process')),
                IF(seq % 5 < 2, {$type}, NULL),
                IF(seq % 5 < 2, CAST(seq % 20000 + 1 AS CHAR), NULL),
                IF(seq % 5 < 2, CONCAT('Record #', seq % 20000 + 1, ' saved'), NULL),
                ELT(1 + seq % 4, 'admin', 'admin', 'integration', 'cli'),
                ELT(1 + seq % 5, 'Jane Doe', 'John Smith', 'ERP Sync', 'Mette Hansen', 'bin/magento'),
                'success', IF(seq % 3 = 0, 1, 0),
                {$firstMs} + seq * {$stepMs},
                FROM_UNIXTIME(FLOOR(({$firstMs} + seq * {$stepMs}) / 1000))
            FROM seq_1_to_" . self::ROWS
        );

        $connection->query(
            'INSERT INTO ' . $this->table(EntityChangeStore::TABLE) . " (activity_id, entity_type, entity_id,
                operation, diff_mode, unchanged_count)
            SELECT entity_id, subject_type, subject_id, 'update', 'changed', 0 FROM {$journal}
            WHERE correlation_id LIKE '" . self::CORRELATION_PREFIX . "%' AND channel = 'entity'"
        );

        $connection->query(
            'INSERT INTO ' . $this->table(EntityChangeStore::FIELD_TABLE) . " (activity_id, scope_type, scope_id,
                scope_label, field, before_value, after_value, is_changed, is_masked)
            SELECT c.activity_id,
                IF(c.entity_type = 'config_value' AND c.activity_id % 3 = 0, 'website', 'default'),
                IF(c.entity_type = 'config_value' AND c.activity_id % 3 = 0, 1, 0),
                IF(c.entity_type = 'config_value' AND c.activity_id % 3 = 0, 'Main Website', 'Default Config'),
                IF(c.entity_type = 'config_value',
                    IF(c.activity_id % 997 = 0, '" . self::RARE_PATH . "',
                        CONCAT('section', c.activity_id % 40, '/group', c.activity_id % 7, '/field', s.seq)),
                    ELT(1 + (c.activity_id + s.seq) % 8, 'price', 'name', 'status', 'description',
                        'special_price', 'visibility', 'meta_title', 'qty')),
                CONCAT('Before ', c.activity_id, IF(c.activity_id % 13 = 0, ' soft cotton shirt', ' plain text')),
                CONCAT('After ', c.activity_id, IF(c.activity_id % 17 = 0, ' organic cotton tee', ' new text')),
                IF((c.activity_id + s.seq) % 5 = 0, 0, 1),
                IF(c.activity_id % 50 = 0, 1, 0)
            FROM " . $this->table(EntityChangeStore::TABLE) . ' c
            JOIN ' . $journal . " j ON j.entity_id = c.activity_id
                AND j.correlation_id LIKE '" . self::CORRELATION_PREFIX . "%'
            JOIN seq_1_to_3 s ON s.seq <= 2 + c.activity_id % 2"
        );
        $connection->query('ANALYZE TABLE ' . $journal . ', ' . $this->table(EntityChangeStore::TABLE) . ', '
            . $this->table(EntityChangeStore::FIELD_TABLE));
    }

    /**
     * Remove the seeded activities; their changes go with them
     *
     * @return void
     */
    public function remove(): void
    {
        $connection = $this->resourceConnection->getConnection();
        $journal = $this->table(self::JOURNAL_TABLE);
        $firstId = $connection->fetchOne(
            $connection->select()
                ->from($journal, ['MIN(entity_id)'])
                ->where('correlation_id LIKE ?', self::CORRELATION_PREFIX . '%')
        );
        if (is_numeric($firstId)) {
            $connection->delete($journal, [
                'entity_id >= ?' => (int) $firstId,
                'correlation_id LIKE ?' => self::CORRELATION_PREFIX . '%',
            ]);
        }
    }

    /**
     * Id of the product changed most recently, which has changes in any window ending now
     *
     * @return string
     */
    public function recentProduct(): string
    {
        $connection = $this->resourceConnection->getConnection();
        $id = $connection->fetchOne(
            $connection->select()
                ->from($this->table(EntityChangeStore::TABLE), ['entity_id'])
                ->where('entity_type = ?', 'product')
                ->order('activity_id DESC')
                ->limit(1)
        );

        return is_numeric($id) ? (string) $id : '1';
    }

    /**
     * Seeded journal rows present
     *
     * @return int
     */
    private function seededRows(): int
    {
        $connection = $this->resourceConnection->getConnection();
        $count = $connection->fetchOne(
            $connection->select()
                ->from($this->table(self::JOURNAL_TABLE), ['COUNT(*)'])
                ->where('correlation_id LIKE ?', self::CORRELATION_PREFIX . '%')
        );

        return is_numeric($count) ? (int) $count : 0;
    }

    /**
     * A table's name
     *
     * @param string $name
     * @return string
     */
    private function table(string $name): string
    {
        return $this->resourceConnection->getTableName($name);
    }
}
